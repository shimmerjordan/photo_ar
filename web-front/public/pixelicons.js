/**
 * 网格字符串 → 一组 `<rect>`。
 *
 * **显式丢前导空白**（那个坑见模块说明），并把不足 16 列的行右侧留空、不足 16 行的
 * 上下居中 —— 这样源码里的图不必写满 16×16 也能对齐到网格中心。
 */
function rects(grid) {
  const rows = grid.split('\n').map((l) => l.replace(/^\s+/, '').replace(/\s+$/, '')).filter(Boolean)
  if (rows.length > 16) throw new Error(`图标超过 16 行：${rows.length}`)
  const cols = Math.max(...rows.map((r) => r.length))
  if (cols > 16) throw new Error(`图标超过 16 列：${cols}`)
  const dx = Math.floor((16 - cols) / 2)
  const dy = Math.floor((16 - rows.length) / 2)
  const out = []
  rows.forEach((row, y) => {
    let run = 0
    for (let x = 0; x <= row.length; x++) {
      if (row[x] === '#') { run++; continue }
      if (run) {
        // 同一行连续的格子合成一个 rect —— 一张图从上百个 rect 降到十几个，
        // 而底栏上有五张图、每次切页签都重绘。
        out.push(`<rect x="${dx + x - run}" y="${dy + y}" width="${run}" height="1"/>`)
        run = 0
      }
    }
  })
  return out.join('')
}

const CACHE = new Map()

/**
 * 一张图标的内联 SVG。
 *
 * `currentColor` + `crispEdges`：颜色跟随文字（底栏选中/未选中只改一个 CSS 变量），
 * 而 crispEdges 是这套风格的硬要求 —— 缺了它 16 格的边会被抗锯齿抹成灰。
 */
export function icon(name, size = 16) {
  const key = `${name}:${size}`
  if (CACHE.has(key)) return CACHE.get(key)
  const grid = G[name]
  if (!grid) throw new Error(`没有这张图标：${name}`)
  const svg =
    `<svg class="ico" viewBox="0 0 16 16" width="${size}" height="${size}" ` +
    `fill="currentColor" shape-rendering="crispEdges" aria-hidden="true">${rects(grid)}</svg>`
  CACHE.set(key, svg)
  return svg
}

/** 全部图标名。给测试用（"没有两张一样"那一条要遍历它）。 */
export const ICON_NAMES = Object.keys(G)

/** 某张图标的实心格子集合。测试用它比对两张图是否相同。 */
export function iconCells(name) {
  const rows = G[name].split('\n').map((l) => l.trim()).filter(Boolean)
  return rows.join('|')
}
