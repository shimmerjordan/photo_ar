/**
 * 相纸尺寸预设。
 *
 * ## 这一层现在是**纯元数据**
 *
 * 网页版走的是单应矩阵四角那条纯 2D 路：视频面片就是照片本身那个四边形，不需要知道
 * 照片印出来有多宽。所以填不填、填得准不准，对识别与贴合**一点影响都没有**。
 *
 * 那为什么还留着：这个宽度会随入库写进 catalog（`photo.print_width_m`），而服务端的
 * 离线评测语料仍然按它建（`corpus.py` 的清单行要一个正的物理宽度）。
 * 拆掉这一层要动数据库那一列，收益只是少一个可留空的输入框 —— 不值得。
 *
 * 历史：这个输入框曾经是**必要**的。安卓客户端用 ARCore Augmented Image 做真 6DoF
 * 贴合，填了宽度它一认出图案就能直接给位姿，不填就要用户晃手机让它自己量尺度
 * （不晃就会超时丢掉整次命中）。安卓那一半 2026-08-05 下线了，所以它降级成元数据。
 * 写下来是因为界面上那句"识别和贴合都不看它"看起来像"那问它干什么" —— 答案在上面。
 *
 * ## 横竖两个方向都列出来
 *
 * 同一张 6 寸照片横放宽 152、竖放宽 102。让程序去猜方向的话，猜错就是宽高对调。
 *
 * ## 用一排标签而不是下拉框
 *
 * 下拉框会把选项藏起来，于是大多数人根本不知道有得选。
 */
