/**
 * 这个 App 的像素图标。**原创的**，不是从图标库描的。
 *
 * ## 网格是 16×16，不是 12 也不是 24
 *
 * 16 是这套图标唯一的硬约束，三件事同时要求它：
 *
 * - **24dp 的图标框里，16 格 = 每格 1.5dp。** 在 xxhdpi（3x）上就是 4.5 物理像素一格 ——
 *   够粗到看得出是像素画。12 格会粗得像马赛克，24 格在 24dp 里每格只剩 1dp，
 *   缩到一半就和普通线性图标区分不开了，那时候「像素风」这件事就白做了。
 * - 16×16 是像素画的传统图标尺寸（NES 的一个 tile 是 8×8，两块拼一个图标），所以
 *   这个网格上的取舍是有前人经验的：对称轴在第 8 格、斜线只能走 45°、
 *   一格宽的线在小尺寸下会断。
 * - 偶数格才有真正的中心线（第 8/9 格之间），而这套图标里有一半是左右对称的。
 *
 * 所以下面每一张都是 16 行 × 16 列。多一行少一列都会让它和别的图标对不齐 ——
 * [PixelIcon] 是按短边算格子的，行数不同的图标在同一个 24dp 框里格子大小就不同，
 * 摆在一排会有的粗有的细。
 *
 * ## 为什么不用 Material 的图标
 *
 * 原来底栏用的是 `Icons.Filled.Home / List / Settings / Add`。那几个是矢量描边图，
 * 抗锯齿的曲线 —— 和像素风放在一起是最刺眼的那种不一致（用户第一眼看到的就是
 * 「有几个图标不对劲」）。而这套只有五六个图标，自己画完全划得来。
 */
