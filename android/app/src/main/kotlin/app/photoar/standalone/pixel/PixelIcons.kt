     *
     * 三条判据是从这三次失败里反推出来的：
     *
     * 1. **轮身必须实心**且占大部分面积。空心 = 甜甜圈。
     * 2. **齿必须小**，只伸出一格。齿一大就成了花瓣或十字 —— 读者看到的主形状变成
