     * ## 这张画错了三版，三次都是同一个错法
     *
     * 齿轮是这套图标里最难的一个，因为它是**圆的**，而 16 格上没有圆。三次失败：
     * 齿和轮身连成一片（读成一朵花）、轮身做成环形（读成甜甜圈）、四颗大齿从空心
